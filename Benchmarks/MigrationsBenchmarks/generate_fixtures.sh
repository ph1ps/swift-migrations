#!/bin/bash
# Generates synthetic DAG fixture types for benchmarking. Not part of the
# build — run manually to regenerate GeneratedFixtures.swift if shapes/sizes
# change.
#
# Chain/fanin/tree fixtures need real (non-empty) `dependencies`, and
# SyncMigration/AsyncMigration each declare their own independently-typed
# `dependencies` requirement — one property can't satisfy both, so those
# shapes generate separate Sync and Async types. Fanout nodes have no
# dependencies at all (default `[]` satisfies both), so they stay
# dual-conformance and shared between the two benchmarks. `Migration.id` has
# no default, so every struct declares one explicitly (its own name, unique
# by construction).
set -euo pipefail
OUT="$(dirname "$0")/GeneratedFixtures.swift"

migrate_body() {
  local kind=$1
  if [[ "$kind" == "Sync" ]]; then
    echo -n "func migrate() throws {}"
  else
    echo -n "func migrate() async throws {}"
  fi
}

emit_chain() {
  local n=$1
  local kind=$2
  local prefix="Chain${n}${kind}Node"
  echo "struct ${prefix}0: ${kind}Migration { static let id = MigrationID(\"${prefix}0\"); $(migrate_body "$kind") }"
  for ((i=1; i<n; i++)); do
    prev=$((i-1))
    echo "struct ${prefix}${i}: ${kind}Migration { static let id = MigrationID(\"${prefix}${i}\"); static var dependencies: [any ${kind}Migration.Type] { [${prefix}${prev}.self] }; $(migrate_body "$kind") }"
  done
}

emit_fanout() {
  local n=$1
  local prefix="Fanout${n}Node"
  for ((i=0; i<n; i++)); do
    echo "struct ${prefix}${i}: SyncMigration, AsyncMigration { static let id = MigrationID(\"${prefix}${i}\"); func migrate() throws {}; func migrate() async throws {} }"
  done
}

emit_fanin() {
  local n=$1
  local kind=$2
  local prefix="Fanin${n}${kind}Node"
  for ((i=0; i<n-1; i++)); do
    echo "struct ${prefix}${i}: ${kind}Migration { static let id = MigrationID(\"${prefix}${i}\"); $(migrate_body "$kind") }"
  done
  echo -n "struct ${prefix}Root: ${kind}Migration { static let id = MigrationID(\"${prefix}Root\"); static var dependencies: [any ${kind}Migration.Type] { ["
  for ((i=0; i<n-1; i++)); do
    echo -n "${prefix}${i}.self"
    if (( i < n-2 )); then echo -n ", "; fi
  done
  echo -n "] }; "
  migrate_body "$kind"
  echo " }"
}

emit_tree() {
  local n=$1
  local kind=$2
  local prefix="Tree${n}${kind}Node"
  echo "struct ${prefix}0: ${kind}Migration { static let id = MigrationID(\"${prefix}0\"); $(migrate_body "$kind") }"
  for ((i=1; i<n; i++)); do
    parent=$(( (i-1)/2 ))
    echo "struct ${prefix}${i}: ${kind}Migration { static let id = MigrationID(\"${prefix}${i}\"); static var dependencies: [any ${kind}Migration.Type] { [${prefix}${parent}.self] }; $(migrate_body "$kind") }"
  done
}

emit_array() {
  local kind=$1   # Sync or Async
  local varname=$2
  local prefix=$3
  local n=$4
  local extra_name=${5:-}  # extra single node name (e.g. Root), appended after the numbered ones
  echo -n "let ${varname}${kind}: [any ${kind}Migration] = ["
  local first=1
  for ((i=0; i<n; i++)); do
    if [[ $first -eq 0 ]]; then echo -n ", "; fi
    echo -n "${prefix}${i}()"
    first=0
  done
  if [[ -n "$extra_name" ]]; then
    echo -n ", ${prefix}${extra_name}()"
  fi
  echo "]"
}

{
  echo "// Generated by generate_fixtures.sh — do not edit by hand."
  echo "import Migrations"
  echo

  for n in 10 100 1000; do
    emit_chain "$n" Sync
    emit_chain "$n" Async
    emit_fanout "$n"
    emit_fanin "$n" Sync
    emit_fanin "$n" Async
    emit_tree "$n" Sync
    emit_tree "$n" Async
    echo
    emit_array Sync "chain${n}" "Chain${n}SyncNode" "$n"
    emit_array Async "chain${n}" "Chain${n}AsyncNode" "$n"
    emit_array Sync "fanout${n}" "Fanout${n}Node" "$n"
    emit_array Async "fanout${n}" "Fanout${n}Node" "$n"
    emit_array Sync "fanin${n}" "Fanin${n}SyncNode" "$((n-1))" "Root"
    emit_array Async "fanin${n}" "Fanin${n}AsyncNode" "$((n-1))" "Root"
    emit_array Sync "tree${n}" "Tree${n}SyncNode" "$n"
    emit_array Async "tree${n}" "Tree${n}AsyncNode" "$n"
    echo
  done
} > "$OUT"

echo "Wrote $(wc -l < "$OUT") lines to $OUT"
